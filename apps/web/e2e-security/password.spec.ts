import { expect, test } from '@playwright/test';
test('troca de senha exige confirmação, encerra todas as sessões e permite novo login', async ({ page, browser }) => {
  const email = process.env.E2E_EMAIL!;
  const oldPassword = process.env.E2E_PASSWORD!;
  const newPassword = `${oldPassword}-changed`;
  await page.goto('/');
  await page.getByLabel('Email', { exact: true }).fill(email);
  await page.getByLabel('Senha', { exact: true }).fill(oldPassword);
  await page.getByRole('button', { name: 'Entrar', exact: true }).click();
  await expect(page.getByRole('link', { name: 'Segurança da conta', exact: true })).toBeVisible();
  const origin = new URL(page.url()).origin;
  const other = await browser.newContext();
  try {
    expect((await other.request.post(`${origin}/api/v1/auth/login`, { headers: { Origin: origin }, data: { email, password: oldPassword } })).status()).toBe(200);
    await page.getByRole('link', { name: 'Segurança da conta', exact: true }).click();
    await expect(page.getByRole('heading', { name: 'Segurança da conta' })).toBeFocused();
    await expect(page).toHaveTitle('Segurança da conta · FlagPilot');
    await page.setViewportSize({ width: 390, height: 844 });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
    await page.getByLabel('Senha atual', { exact: true }).fill(oldPassword);
    await page.getByLabel('Nova senha', { exact: true }).fill(newPassword);
    await page.getByLabel('Confirmar nova senha', { exact: true }).fill('different-confirmation');
    await page.getByRole('button', { name: 'Alterar senha e sair', exact: true }).click();
    await expect(page.getByText('As senhas não coincidem.', { exact: true })).toBeVisible();
    await page.getByLabel('Senha atual', { exact: true }).fill('wrong-current-password');
    await page.getByLabel('Confirmar nova senha', { exact: true }).fill(newPassword);
    await page.getByRole('button', { name: 'Alterar senha e sair', exact: true }).click();
    await expect(page.getByRole('alert')).toHaveText('Senha atual incorreta');
    for (const name of ['Senha atual', 'Nova senha', 'Confirmar nova senha']) await expect(page.getByLabel(name, { exact: true })).toHaveValue('');
    await page.getByLabel('Senha atual', { exact: true }).fill(oldPassword);
    await page.getByLabel('Nova senha', { exact: true }).fill(newPassword);
    await page.getByLabel('Confirmar nova senha', { exact: true }).fill(newPassword);
    await page.getByRole('button', { name: 'Alterar senha e sair', exact: true }).click();
    await expect(page.getByRole('status')).toHaveText('Senha alterada. Todas as sessões foram encerradas. Entre novamente com sua nova senha.');
    await expect(page.getByLabel('Email', { exact: true })).toBeFocused();
    expect((await other.request.get(`${origin}/api/v1/me`)).status()).toBe(401);
    expect((await page.request.get(`${origin}/api/v1/me`)).status()).toBe(401);
    await page.getByLabel('Email', { exact: true }).fill(email);
    await page.getByLabel('Senha', { exact: true }).fill(oldPassword);
    await page.getByRole('button', { name: 'Entrar', exact: true }).click();
    await expect(page.getByRole('alert')).toHaveText('Email ou senha inválidos');
    await page.getByLabel('Senha', { exact: true }).fill(newPassword);
    await page.getByRole('button', { name: 'Entrar', exact: true }).click();
    await expect(page.getByRole('link', { name: 'Segurança da conta', exact: true })).toBeVisible();
    expect(await page.evaluate(() => localStorage.length + sessionStorage.length)).toBe(0);
    const me = await (await page.request.get('/api/v1/me')).json();
    const history = await (await page.request.get(`/api/v1/organizations/${me.memberships[0].organizationId}/audit-events?action=auth.password_changed`)).text();
    expect(history).toContain('auth.password_changed');
    expect(history).not.toContain(oldPassword); expect(history).not.toContain(newPassword);
    await page.goto(`/organizations/${me.memberships[0].organizationId}/audit`);
    await expect(page.getByLabel('Ação', { exact: true }).getByRole('option', { name: 'auth.password_changed', exact: true })).toHaveCount(1);
    await page.getByLabel('Ação', { exact: true }).selectOption('auth.password_changed');
    await page.getByRole('button', { name: 'Aplicar filtros', exact: true }).click();
    await expect(page.getByRole('listitem').filter({ hasText: 'auth.password_changed' })).toHaveCount(1);
  } finally { await other.close(); }
});
