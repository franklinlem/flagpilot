import { expect, test } from '@playwright/test';
test('projetos e ambientes, produção explícita e Viewer em leitura', async ({ page, browser }) => {
  await page.goto('/');
  await page.getByLabel('Email', { exact: true }).fill(process.env.E2E_EMAIL!);
  await page.getByLabel('Senha', { exact: true }).fill(process.env.E2E_PASSWORD!);
  await page.getByRole('button', { name: 'Entrar', exact: true }).click();
  await page.getByRole('listitem').filter({ hasText: 'E2E Organization' }).getByRole('link', { name: 'Ver projetos' }).click();
  await expect(page.getByRole('heading', { name: 'Projetos da organização' })).toBeVisible();
  await page.getByRole('button', { name: 'Novo projeto', exact: true }).click();
  await page.getByLabel('Nome do projeto').fill('Loja E2E');
  await page.getByLabel('Slug do projeto').fill('loja-e2e');
  await page.getByRole('button', { name: 'Criar projeto', exact: true }).click();
  await page.getByRole('listitem').filter({ hasText: 'Loja E2E' }).getByRole('link', { name: 'Ver ambientes' }).click();
  await expect(page.getByRole('listitem')).toHaveCount(3);
  await expect(page.getByRole('listitem').filter({ hasText: 'production' }).getByText('Produção', { exact: true })).toHaveCount(2);
  await page.getByRole('button', { name: 'Novo ambiente', exact: true }).click();
  await page.getByLabel('Nome do ambiente').fill('Produção Europa');
  await page.getByLabel('Slug do ambiente').fill('eu-live');
  await page.getByLabel('Este ambiente é de produção').check();
  await page.getByRole('button', { name: 'Criar ambiente', exact: true }).click();
  const custom = page.getByRole('listitem').filter({ hasText: 'eu-live' });
  await expect(custom.getByText('Produção', { exact: true })).toBeVisible();
  await expect(page.getByRole('listitem')).toHaveCount(4);
  await page.reload();
  await expect(custom).toBeVisible();
  await page.getByRole('button', { name: 'Novo ambiente', exact: true }).click();
  await page.getByLabel('Nome do ambiente').fill('Duplicado');
  await page.getByLabel('Slug do ambiente').fill('staging');
  await page.getByRole('button', { name: 'Criar ambiente', exact: true }).click();
  await expect(page.getByRole('alert')).toHaveText('slug já utilizado neste escopo');
  await page.getByRole('button', { name: 'Fechar formulário', exact: true }).click();
  const projectPath = new URL(page.url()).pathname;
  const projectId = projectPath.split('/')[2];
  const identity = await (await page.request.get('/api/v1/me')).json();
  const orgId = identity.memberships.find((item: { organizationName: string }) => item.organizationName === 'E2E Organization').organizationId;
  const privateOrg = await page.request.post('/api/v1/organizations', { headers: { Origin: new URL(page.url()).origin, 'X-CSRF-Token': identity.csrfToken }, data: { name: 'Escopo privado E2E', slug: 'private-projects-e2e' } });
  expect(privateOrg.status()).toBe(201);
  const privateOrgId = (await privateOrg.json()).id;
  const privateProject = await page.request.post(`/api/v1/organizations/${privateOrgId}/projects`, { headers: { Origin: new URL(page.url()).origin, 'X-CSRF-Token': identity.csrfToken }, data: { name: 'Privado', slug: 'private-project' } });
  expect(privateProject.status()).toBe(201);
  const privateProjectId = (await privateProject.json()).id;
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  const viewerContext = await browser.newContext();
  try {
    const viewer = await viewerContext.newPage();
    await viewer.goto(new URL('/', page.url()).toString());
    await viewer.getByLabel('Email', { exact: true }).fill(process.env.E2E_VIEWER_EMAIL!);
    await viewer.getByLabel('Senha', { exact: true }).fill(process.env.E2E_VIEWER_PASSWORD!);
    await viewer.getByRole('button', { name: 'Entrar', exact: true }).click();
    await viewer.getByRole('link', { name: 'Ver projetos' }).click();
    await expect(viewer.getByRole('button', { name: 'Novo projeto', exact: true })).toHaveCount(0);
    await viewer.getByRole('listitem').filter({ hasText: 'Loja E2E' }).getByRole('link', { name: 'Ver ambientes' }).click();
    await expect(viewer.getByRole('listitem')).toHaveCount(4);
    await expect(viewer.getByRole('button', { name: 'Novo ambiente', exact: true })).toHaveCount(0);
    await expect(viewer.getByRole('link', { name: 'Gerenciar tokens', exact: true })).toHaveCount(0);
    const viewerEnvPath = await viewer.getByRole('link', { name: 'Configurar flags', exact: true }).first().getAttribute('href');
    expect((await viewer.request.get(`/api/v1/environments/${viewerEnvPath!.split('/')[2]}/tokens`)).status()).toBe(403);
    const profile = await (await viewer.request.get('/api/v1/me')).json();
    const headers = { Origin: new URL(page.url()).origin, 'X-CSRF-Token': profile.csrfToken };
    expect((await viewer.request.post(`/api/v1/organizations/${orgId}/projects`, { headers, data: { name: 'Forbidden', slug: 'forbidden' } })).status()).toBe(403);
    expect((await viewer.request.post(`/api/v1/projects/${projectId}/environments`, { headers, data: { name: 'Forbidden', slug: 'forbidden', isProduction: false } })).status()).toBe(403);
    expect((await viewer.request.get(`/api/v1/projects/${privateProjectId}`)).status()).toBe(404);
    await viewer.goto(new URL(`/organizations/${orgId}/audit`,page.url()).toString());
    await expect(viewer.getByRole('heading',{name:'Histórico de auditoria'})).toBeVisible();
    await expect(viewer.getByRole('listitem').first()).toBeVisible();
    expect((await viewer.request.get(`/api/v1/organizations/${privateOrgId}/audit-events`)).status()).toBe(404);
  } finally { await viewerContext.close(); }
});
