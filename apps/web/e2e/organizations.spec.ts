import { expect, test } from '@playwright/test';
test('organizações, membros, último Owner e Viewer sem privilégios', async ({ page, browser }) => {
  const email = process.env.E2E_EMAIL!;
  const viewerEmail = process.env.E2E_VIEWER_EMAIL!;
  const viewerID = process.env.E2E_VIEWER_ID!;
  await page.goto('/');
  await page.getByLabel('Email', { exact: true }).fill(email);
  await page.getByLabel('Senha', { exact: true }).fill(process.env.E2E_PASSWORD!);
  await page.getByRole('button', { name: 'Entrar', exact: true }).click();
  await page.getByRole('button', { name: 'Nova organização', exact: true }).click();
  await page.getByLabel('Nome da organização').fill('Segunda organização');
  await page.getByLabel('Slug da organização').fill('second-e2e');
  await page.getByRole('button', { name: 'Criar organização', exact: true }).click();
  const second = page.getByRole('listitem').filter({ hasText: 'Segunda organização' });
  await expect(second).toBeVisible();
  const foreignPath = await second.getByRole('link', { name: 'Ver membros' }).getAttribute('href');
  const original = page.getByRole('listitem').filter({ hasText: 'E2E Organization' });
  await original.getByRole('link', { name: 'Ver membros' }).click();
  await expect(page.getByRole('heading', { name: 'Membros da organização' })).toBeVisible();
  const orgId = page.url().split('/organizations/')[1].split('/')[0];
  const owner = page.getByRole('listitem').filter({ has: page.getByText(email, { exact: true }) });
  await owner.getByLabel(`Papel de ${email}`).selectOption('Viewer');
  await owner.getByRole('button', { name: 'Salvar papel', exact: true }).click();
  await expect(owner.getByRole('alert')).toHaveText('a organização precisa manter ao menos um Proprietário ativo');
  const viewer = page.getByRole('listitem').filter({ has: page.getByText(viewerEmail, { exact: true }) });
  await viewer.getByLabel(`Papel de ${viewerEmail}`).selectOption('Editor');
  await viewer.getByRole('button', { name: 'Salvar papel', exact: true }).click();
  await expect(viewer.getByLabel(`Papel de ${viewerEmail}`)).toHaveValue('Editor');
  await expect(viewer.getByRole('button', { name: 'Salvar papel', exact: true })).toBeDisabled();
  await expect(viewer.getByRole('button', { name: 'Salvar papel', exact: true })).toHaveCSS('cursor', 'default');
  await viewer.getByRole('button', { name: 'Remover membro', exact: true }).click();
  await viewer.getByRole('button', { name: 'Confirmar remoção', exact: true }).click();
  await expect(viewer).toHaveCount(0);
  await expect(page.getByLabel('Usuário existente', { exact: true }).getByRole('option', { name: viewerEmail, exact: true })).toHaveCount(1);
  await page.getByLabel('Usuário existente', { exact: true }).selectOption({ label: viewerEmail });
  await page.getByRole('button', { name: 'Adicionar membro', exact: true }).click();
  await expect(viewer.getByLabel(`Papel de ${viewerEmail}`)).toHaveValue('Viewer');
  const viewerContext = await browser.newContext();
  try {
    const other = await viewerContext.newPage();
    await other.goto(new URL('/', page.url()).toString());
    await other.getByLabel('Email', { exact: true }).fill(viewerEmail);
    await other.getByLabel('Senha', { exact: true }).fill(process.env.E2E_VIEWER_PASSWORD!);
    await other.getByRole('button', { name: 'Entrar', exact: true }).click();
    await expect(other.getByText('Segunda organização', { exact: true })).toHaveCount(0);
    await other.getByRole('link', { name: 'Ver membros' }).click();
    await expect(other.getByText('Somente Proprietários podem gerenciar membros.')).toBeVisible();
    await expect(other.getByRole('button', { name: 'Remover membro', exact: true })).toHaveCount(0);
    const identity = await (await other.request.get('/api/v1/me')).json();
    const denied = await other.request.patch(`/api/v1/organizations/${orgId}/members/${viewerID}`, { headers: { Origin: new URL(page.url()).origin, 'X-CSRF-Token': identity.csrfToken }, data: { role: 'Owner' } });
    expect(denied.status()).toBe(403);
    expect((await other.request.get(`/api/v1/organizations/${orgId}/member-candidates`)).status()).toBe(403);
    const outside = await other.request.get(`/api/v1${foreignPath!}`);
    expect(outside.status()).toBe(404);
  } finally { await viewerContext.close(); }
});
